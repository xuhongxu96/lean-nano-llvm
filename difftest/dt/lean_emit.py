"""Translation of refinement pairs into Lean proof obligations, and their checking.

Translation is deliberately *not* a re-implementation of LLVM IR in Python: each obligation
file embeds the two functions' ``.ll`` text verbatim as Lean string literals, and the
``ll_def%`` elaborator (``PRELUDE``) parses them at elaboration time with
``LeanNanoLlvm.AST.Parser`` — the same parser ``lean-nano-llvm run`` and the llubi frontend
use — and inserts the resulting ``Definition`` as a concrete AST. The statement therefore
talks about exactly the IR the oracles saw, and a parse failure is reported as a translation
failure rather than hidden.

For each pair we generate up to three independent obligations, each in its own file so that
each attempt is timed and fails in isolation:

* ``prove``: ``src ⊒ tgt`` by ``llvm_refine``.
* ``disprove-witness``: ``¬ (src ⊒ tgt)`` by ``llvm_disprove [w₁, …]``, where the witness is
  Alive2's counterexample (only when every input value is an integer, float or ``poison``).
* ``disprove-search``: ``¬ (src ⊒ tgt)`` by ``llvm_disprove`` (our own bounded witness search).

``src ⊒ tgt`` is ``Definition.IsRefinedByWith .modern .default64LE``: no ``undef`` and
LLVM's default little-endian 64-bit data layout, which is why the primary Alive2 configuration
is ``--disable-undef-input``.
"""

from __future__ import annotations

import re
from pathlib import Path
from typing import Any

from . import ir
from .common import REPO, run, sha256

PRELUDE = '''import LeanNanoLlvm.Refinement
import LeanNanoLlvm.AST.Parser
import LeanNanoLlvm.AST.Syntax  -- `ToExpr` instances for the AST

/-! Generated by difftest/dt/lean_emit.py. Do not edit. -/

open Lean Elab Term Meta in
/-- `ll_def% "<module text>" "<function>"`: the `Definition` of `@<function>` in a `.ll`
module, parsed by `LeanNanoLlvm.AST.Parser` at elaboration time. -/
elab "ll_def% " s:str n:str : term => do
  match LeanNanoLlvm.AST.Parser.parseLlvmModule s.getString with
  | .error e => throwError "ll_def%: parse error: {e}"
  | .ok pm =>
    let name := n.getString
    let found := pm.topLevel.entities.findSome? fun
      | .definition d => if d.prototype.name == .name name then some d else none
      | _ => none
    match found with
    | some d => return toExpr d
    | none => throwError "ll_def%: no definition of @{name}"

open LeanNanoLlvm Semantics Refinement
'''

OBLIGATIONS = ["prove", "disprove-witness", "disprove-search"]

# The fixed proof script of the `prove` obligation: symbolic execution and verification-condition
# generation (`llvm_refine`), then a fixed portfolio of standard-axiom closers for the remaining
# pure goals. `bv_decide` is deliberately absent: it relies on `Lean.ofReduceBool`.
PROVE_SCRIPT = """llvm_refine
  all_goals first
    | (simp_all; done)
    | bv_omega
    | grind"""

STANDARD_AXIOMS = {"propext", "Classical.choice", "Quot.sound"}
AXIOMS_RE = re.compile(r"depends on axioms: \[([^\]]*)\]")


def lean_string(s: str) -> str:
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"').replace("\t", "\\t") + '"'


def standalone_function(module: str, fn: str, rename: str = "f") -> str:
    """The module with `@fn` renamed to `@rename` (declarations and globals are kept, since
    the function may reference them)."""
    pat = re.compile(r"@" + re.escape(fn) + r"(?![-\w.$])")
    return pat.sub("@" + rename, module)


def witness_term(cex: list[dict[str, Any]]) -> str | None:
    terms = []
    for v in cex:
        val = v.get("value", {})
        ty = v.get("type", "")
        m = re.fullmatch(r"i(\d+)", ty)
        if val.get("kind") == "poison" and m:
            terms.append(f"RegisterValue.bv {m.group(1)} PoisonOr.poison")
        elif val.get("kind") == "int":
            terms.append(f"RegisterValue.bv {val['width']} (PoisonOr.value (BitVec.ofNat {val['width']} {val['bits']}))")
        elif val.get("kind") == "float":
            terms.append(f"RegisterValue.float FloatType.{val['type']} (PoisonOr.value {{ bits := BitVec.ofNat _ {val['bits']} }})")
        elif val.get("kind") == "poison" and ty in ("half", "bfloat", "float", "double"):
            terms.append(f"RegisterValue.float FloatType.{ty} PoisonOr.poison")
        else:
            return None
    return "[" + ", ".join(terms) + "]"


def obligation(kind: str, src_mod: str, src_fn: str, tgt_mod: str, tgt_fn: str,
               witness: str | None = None, name: str = "case") -> str | None:
    src = f"ll_def% {lean_string(standalone_function(src_mod, src_fn))} \"f\""
    tgt = f"ll_def% {lean_string(standalone_function(tgt_mod, tgt_fn))} \"f\""
    if kind == "prove":
        stmt, tac = f"{src} ⊒\n  {tgt}", PROVE_SCRIPT
    elif kind == "disprove-witness":
        if witness is None:
            return None
        stmt, tac = f"¬ ({src} ⊒\n  {tgt})", f"llvm_disprove {witness}"
    elif kind == "disprove-search":
        stmt, tac = f"¬ ({src} ⊒\n  {tgt})", "llvm_disprove"
    else:
        raise ValueError(kind)
    return PRELUDE + f"\ntheorem {name} :\n  {stmt} := by\n  {tac}\n\n#print axioms {name}\n"


LEAN_ERR_RE = re.compile(r"^(?P<file>[^:\n]+):(?P<line>\d+):(?P<col>\d+): error: (?P<msg>.*)$", re.M)


def classify_lean(exit_code: int | None, timeout: bool, out: str) -> tuple[str, str]:
    """(status, message) for one obligation check: ``checked`` (kernel-checked, standard axioms
    only), ``nonstandard-axioms`` (checked but depends on another axiom), ``translation-error``
    (``ll_def%`` failed: our parser rejected the IR), ``failed`` (the tactic failed),
    ``timeout``, or ``error`` (anything else)."""
    if timeout:
        return "timeout", ""
    m = LEAN_ERR_RE.search(out)
    if exit_code == 0 and not m:
        ax = AXIOMS_RE.search(out)
        used = {a.strip() for a in ax.group(1).split(",") if a.strip()} if ax else set()
        if used - STANDARD_AXIOMS:
            return "nonstandard-axioms", ", ".join(sorted(used - STANDARD_AXIOMS))
        return "checked", ""
    msg = m.group("msg") if m else out.strip().splitlines()[-1] if out.strip() else ""
    if "ll_def%" in out and ("parse error" in out or "no definition" in out):
        return "translation-error", msg[:500]
    if m:
        return "failed", msg[:500]
    return "error", msg[:500]


def check_obligation(text: str, workdir: Path, timeout: float = 300.0, mem_mb: int = 8192) -> dict[str, Any]:
    """Elaborate one obligation with `lake env lean` (kernel-checked, standard axioms only)."""
    workdir.mkdir(parents=True, exist_ok=True)
    f = workdir / f"{sha256(text)[:16]}.lean"
    f.write_text(text)
    r = run(["lake", "env", "lean", str(f)], timeout=timeout, mem_mb=mem_mb, cwd=REPO)
    status, msg = classify_lean(r.exit, r.timeout, r.stdout + r.stderr)
    return {"status": status, "message": msg, "wall_s": r.wall_s, "file": str(f.relative_to(workdir.parent))
            if workdir.parent in f.parents else str(f)}


def pair_is_translatable(src_mod: str, tgt_mod: str) -> list[str]:
    """Static reasons why a pair is outside the function-level refinement statement
    (reported as such, not as prover failures)."""
    reasons = []
    for t in (src_mod, tgt_mod):
        if re.search(r"^@[-\w.$\"]+ = ", t, re.M):
            reasons.append("references-globals")
        calls = [c for c in re.findall(r"call [^@]*@([-\w.$\"]+)\(", t) if not c.startswith("llvm.")]
        if calls:
            reasons.append("calls-non-intrinsic")
    return sorted(set(reasons))


def features_of_pair(src_mod: str) -> list[str]:
    return ir.features(src_mod).categories()
