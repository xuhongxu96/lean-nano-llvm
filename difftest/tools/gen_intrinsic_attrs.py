#!/usr/bin/env python3
"""Generate LeanNanoLlvm/Llubi/IntrinsicAttrs.lean: the function attributes LLVM attaches to each
intrinsic declaration, for every intrinsic of the pinned LLVM.

llubi numbers attribute groups with LLVM's slot tracker, which counts the implicit attribute set
of every intrinsic declaration (`Intrinsic::getAttributes`), even when the source writes none.
The llubi frontend needs those sets to print the same `#N`. A declaration's function attributes
depend only on the intrinsic ID (`Intrinsic::getFnAttributes`), not on its overload types, so the
table is keyed by base name (`llvm.umin`) and a mangled name (`llvm.umin.i32`) is resolved as
LLVM's `Intrinsic::lookupIntrinsicID` does: by its longest prefix, at a `.` boundary, that is a
base name.

The sets are printed by `intrinsic_attrs_dump.cpp`, compiled here against the pinned LLVM build
(difftest/tools/build_oracles.sh), with `AttributeSet::getAsString(true)` as LLVM's AsmWriter
prints `attributes #N = { ... }`. All intrinsics of all targets are included.

Usage: gen_intrinsic_attrs.py LLVM_SRC LLVM_BUILD OUT.lean
  e.g. gen_intrinsic_attrs.py difftest/.oracles/src/llvm-project/llvm \\
         difftest/.oracles/build/llvm LeanNanoLlvm/Llubi/IntrinsicAttrs.lean
"""
import glob
import os
import subprocess
import sys
import tempfile

HERE = os.path.dirname(os.path.abspath(__file__))


def main() -> int:
    src, build, out = sys.argv[1:]
    with tempfile.TemporaryDirectory() as d:
        exe = os.path.join(d, "dump")
        libs = sorted(glob.glob(os.path.join(build, "lib", "libLLVM*.a")))
        subprocess.run(["c++", "-std=c++17", "-O1", f"-I{src}/include", f"-I{build}/include",
                        os.path.join(HERE, "intrinsic_attrs_dump.cpp"), "-o", exe,
                        "-Wl,--start-group", *libs, "-Wl,--end-group", "-lpthread", "-lz"],
                       check=True)
        text = subprocess.run([exe], capture_output=True, text=True, check=True).stdout
    sets: list[str] = []
    mapping: list[tuple[str, int]] = []
    total = 0
    for line in text.splitlines():
        name, attrs = line.split("\t", 1)
        total += 1
        if not attrs:
            continue  # no function attributes: no attribute group
        if attrs not in sets:
            sets.append(attrs)
        mapping.append((name, sets.index(attrs)))
    esc = lambda s: s.replace("\\", "\\\\").replace('"', '\\"')
    lines = [
        "/-! Generated by difftest/tools/gen_intrinsic_attrs.py from the pinned LLVM. Do not edit.",
        "",
        "Function attributes LLVM attaches to intrinsic declarations (`Intrinsic::getFnAttributes`),",
        f"for all {total} intrinsics ({len(mapping)} with attributes, {len(sets)} distinct sets),",
        "keyed by base name. -/",
        "",
        "namespace LeanNanoLlvm.Llubi",
        "",
        "/-- The distinct attribute sets, as LLVM prints them inside `attributes #N = { ... }`. -/",
        "def intrinsicAttrSets : Array String := #[",
        ",\n".join(f'  "{esc(s)}"' for s in sets),
        "]",
        "",
        "/-- `name=index` lines: the attribute set (`intrinsicAttrSets`) of each intrinsic, by base name. -/",
        'def intrinsicAttrIndexText : String := "' + "\\n".join(f"{n}={i}" for n, i in mapping) + '"',
        "",
        "end LeanNanoLlvm.Llubi",
        "",
    ]
    open(out, "w").write("\n".join(lines))
    print(f"{total} intrinsics, {len(mapping)} with attributes, {len(sets)} attribute sets -> {out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
