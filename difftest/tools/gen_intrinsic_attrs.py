#!/usr/bin/env python3
"""Generate LeanNanoLlvm/Llubi/IntrinsicAttrs.lean: the function attributes LLVM attaches to each
intrinsic declaration, from the pinned `opt`.

llubi numbers attribute groups with LLVM's slot tracker, which counts the implicit attribute set
of every intrinsic declaration (`Intrinsic::getAttributes`), even when the source writes none.
The llubi frontend needs those sets to print the same `#N`. They come from Intrinsics.td; rather
than re-deriving them, this script declares every intrinsic found in the input `.ll` files, runs
the pinned `opt -S`, and records the attribute set opt prints for each.

Usage: gen_intrinsic_attrs.py OPT OUT.lean FILE_OR_DIR...
"""
import os
import re
import subprocess
import sys
import tempfile

DECL = re.compile(r"^declare [^@]*@(llvm\.[\w.$-]+)\(.*$", re.M)


def main() -> int:
    opt, out, *inputs = sys.argv[1:]
    decls: dict[str, str] = {}
    files = []
    for p in inputs:
        if os.path.isdir(p):
            for root, _, fs in os.walk(p):
                files += [os.path.join(root, f) for f in fs if f.endswith(".ll")]
        else:
            files.append(p)
    for f in sorted(files):
        for m in DECL.finditer(open(f, errors="replace").read()):
            line = re.sub(r"\s+#\d+\s*$", "", m.group(0).split(";")[0].rstrip())
            decls.setdefault(m.group(1), line)
    # the execution drivers declare llvm.memset
    decls.setdefault("llvm.memset.p0.i64", "declare void @llvm.memset.p0.i64(ptr writeonly, i8, i64, i1 immarg)")
    with tempfile.TemporaryDirectory() as d:
        src = os.path.join(d, "decls.ll")
        open(src, "w").write("\n".join(decls.values()) + "\n")
        text = subprocess.run([opt, "-S", src], capture_output=True, text=True, check=True).stdout
    groups = dict(re.findall(r"^attributes #(\d+) = \{ (.*) \}$", text, re.M))
    sets: list[str] = []
    mapping: list[tuple[str, int]] = []
    for m in re.finditer(r"^declare [^@]*@(llvm\.[\w.$-]+)\(.*?\)(?: #(\d+))?$", text, re.M):
        name, grp = m.group(1), m.group(2)
        if grp is None:
            continue
        attrs = groups[grp]
        if attrs not in sets:
            sets.append(attrs)
        mapping.append((name, sets.index(attrs)))
    esc = lambda s: s.replace("\\", "\\\\").replace('"', '\\"')
    lines = [
        "/-! Generated by difftest/tools/gen_intrinsic_attrs.py from the pinned `opt`. Do not edit.",
        "",
        "Function attributes LLVM attaches to intrinsic declarations (`Intrinsic::getAttributes`),",
        f"for the {len(mapping)} intrinsics declared in the difftest corpus ({len(sets)} distinct sets). -/",
        "",
        "namespace LeanNanoLlvm.Llubi",
        "",
        "/-- The distinct attribute sets, as LLVM prints them inside `attributes #N = { ... }`. -/",
        "def intrinsicAttrSets : Array String := #[",
        ",\n".join(f'  "{esc(s)}"' for s in sets),
        "]",
        "",
        "/-- `name=index` lines: the attribute set (`intrinsicAttrSets`) of each intrinsic. -/",
        'def intrinsicAttrIndexText : String := "' + "\\n".join(f"{n}={i}" for n, i in mapping) + '"',
        "",
        "end LeanNanoLlvm.Llubi",
        "",
    ]
    open(out, "w").write("\n".join(lines))
    print(f"{len(mapping)} intrinsics, {len(sets)} attribute sets -> {out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
